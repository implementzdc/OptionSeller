"""
TqSdk 基础连接测试

本程序目前只做一件事情：
    连接天勤服务器，并查询当前可以使用的期货合约。

注意：
1. 不进行任何交易
2. 不连接实盘交易账户
3. 不提交任何订单
4. 账号密码从 .env 文件读取
"""

import os

from dotenv import load_dotenv
from tqsdk import TqApi, TqAuth


def main():
    """
    主程序
    """

    # ============================================================
    # 1. 读取 .env 文件
    # ============================================================

    # load_dotenv() 会自动读取项目根目录下的 .env 文件。
    #
    # .env 中应该类似：
    #
    # TQ_USERNAME=你的快期账号
    # TQ_PASSWORD=你的快期密码
    #
    load_dotenv()

    # 从环境变量中读取账号和密码
    tq_username = os.getenv("TQ_USERNAME")
    tq_password = os.getenv("TQ_PASSWORD")

    # ============================================================
    # 2. 检查账号密码
    # ============================================================

    if not tq_username or not tq_password:
        raise ValueError(
            "没有读取到快期账户信息，请检查项目根目录下的 .env 文件。"
        )

    print("=" * 60)
    print("开始测试 TqSdk 行情接口")
    print("=" * 60)

    # ============================================================
    # 3. 创建 TqApi
    # ============================================================

    # 使用快期账户进行身份认证。
    #
    # 注意：
    # 这里只是连接行情服务器，并不会自动进行交易。
    #
    api = TqApi(
        auth=TqAuth(
            tq_username,
            tq_password
        )
    )

    try:

        # ========================================================
        # 4. 查询当前可用的期货合约
        # ========================================================

        print("\n正在查询期货合约……")

        # query_quotes() 用来查询符合条件的合约。
        #
        # 我们先不指定具体品种，
        # 让天勤把当前可查询到的合约返回给我们。
        #
        # 这里使用期货品种进行筛选。
        quotes = api.query_quotes(
            ins_class="FUTURE"
        )

        print("\n查询成功！")
        print("当前查询到的期货合约数量：", len(quotes))

        # ========================================================
        # 5. 打印前 30 个合约
        # ========================================================

        print("\n前 30 个期货合约：")
        print("-" * 60)

        for i, symbol in enumerate(quotes[:30], start=1):

            print(f"{i:02d}. {symbol}")

        print("-" * 60)

        print("\nTqSdk 基础连接测试完成！")

    finally:

        # ========================================================
        # 6. 关闭连接
        # ========================================================

        api.close()

        print("\nTqSdk 连接已经关闭。")


if __name__ == "__main__":
    main()