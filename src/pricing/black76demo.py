"""
Black-76 期货期权定价演示程序

学习目的：
1. 理解 Black-76 模型是如何给期货期权定价的
2. 理解 Delta、Gamma、Theta、Vega 分别代表什么
3. 观察期货价格发生变化时，期权价格和 Greeks 如何变化

注意：
本程序主要用于学习，不涉及真实交易。
"""

import math

from scipy.stats import norm


# ============================================================
# 1. Black-76 核心计算
# ============================================================

def black76_put(F, K, T, r, sigma):
    """
    使用 Black-76 模型计算期货 Put 的理论价格。

    参数：
        F     : 当前期货价格
        K     : 期权行权价
        T     : 距离到期的时间，单位：年
        r     : 无风险利率，例如 0.02 表示 2%
        sigma : 年化波动率，例如 0.28 表示 28%

    返回：
        Put 的理论价格
    """

    # 当剩余时间或者波动率接近 0 时，
    # 正常的 Black-76 公式会出现除零问题。
    # 这里做一个简单保护。
    if T <= 0 or sigma <= 0:
        return math.exp(-r * T) * max(K - F, 0)

    # Black-76 中的 d1
    d1 = (
        math.log(F / K)
        + 0.5 * sigma ** 2 * T
    ) / (sigma * math.sqrt(T))

    # d2
    d2 = d1 - sigma * math.sqrt(T)

    # Put 价格
    put_price = math.exp(-r * T) * (
        K * norm.cdf(-d2)
        - F * norm.cdf(-d1)
    )

    return put_price


# ============================================================
# 2. 计算 Greeks
# ============================================================

def black76_put_greeks(F, K, T, r, sigma):
    """
    计算 Black-76 Put 的主要 Greeks。

    返回：
        Delta
        Gamma
        Vega
        Theta
    """

    # 防止除零
    if T <= 0 or sigma <= 0:
        return {
            "delta": None,
            "gamma": None,
            "vega": None,
            "theta": None,
        }

    sqrt_T = math.sqrt(T)

    # 计算 d1、d2
    d1 = (
        math.log(F / K)
        + 0.5 * sigma ** 2 * T
    ) / (sigma * sqrt_T)

    d2 = d1 - sigma * sqrt_T

    # 标准正态分布概率密度
    pdf_d1 = norm.pdf(d1)

    # --------------------------------------------------------
    # Delta
    #
    # 对于期货期权：
    #
    # Put Delta = -e^(-rT) * N(-d1)
    #
    # 注意：
    # Delta < 0 是 Put 的基本特征。
    # --------------------------------------------------------

    delta = -math.exp(-r * T) * norm.cdf(-d1)

    # --------------------------------------------------------
    # Gamma
    #
    # Gamma 表示：
    #
    # Delta 对期货价格变化的敏感程度。
    #
    # Gamma 越大：
    # Delta 随着行情变化得越快。
    # --------------------------------------------------------

    gamma = (
        math.exp(-r * T)
        * pdf_d1
        / (F * sigma * sqrt_T)
    )

    # --------------------------------------------------------
    # Vega
    #
    # Vega 表示：
    #
    # 波动率变化 1 个百分点，
    # 期权理论价格大约变化多少。
    #
    # 注意：
    # 这里返回的是“波动率变化 1.00”
    # 时的价格变化，因此最后我们会除以 100，
    # 得到“IV变化1个百分点”的影响。
    # --------------------------------------------------------

    vega = (
        math.exp(-r * T)
        * F
        * pdf_d1
        * sqrt_T
    )

    # --------------------------------------------------------
    # Theta
    #
    # Theta 表示时间流逝对期权价格的影响。
    #
    # 这里为了方便理解，
    # 我们计算“每天”的 Theta。
    # --------------------------------------------------------

    # 先计算一年时间变化对应的 Theta
    theta_year = (
        -math.exp(-r * T)
        * F
        * pdf_d1
        * sigma
        / (2 * sqrt_T)
        + r
        * math.exp(-r * T)
        * (
            K * norm.cdf(-d2)
            - F * norm.cdf(-d1)
        )
    )

    # 一年约 365 天
    theta_day = theta_year / 365

    return {
        "delta": delta,
        "gamma": gamma,
        "vega": vega / 100,  # 换算成 IV 每变化1个百分点
        "theta": theta_day,
    }


# ============================================================
# 3. 主程序
# ============================================================

def main():

    print("=" * 70)
    print("Black-76 期货 Put 期权定价实验")
    print("=" * 70)

    # --------------------------------------------------------
    # 基础参数
    # --------------------------------------------------------

    # 当前生猪期货价格
    F = 10500

    # 行权价
    K = 11000

    # 剩余 25 天
    remaining_days = 25

    # Black-76 使用“年”为时间单位，
    # 所以需要把 25 天转换成 25 / 365 年。
    T = remaining_days / 365

    # 假设无风险利率 2%
    r = 0.02

    # 假设年化波动率 28%
    sigma = 0.28

    # --------------------------------------------------------
    # 计算理论价格
    # --------------------------------------------------------

    put_price = black76_put(
        F,
        K,
        T,
        r,
        sigma
    )

    # --------------------------------------------------------
    # 计算 Greeks
    # --------------------------------------------------------

    greeks = black76_put_greeks(
        F,
        K,
        T,
        r,
        sigma
    )

    # --------------------------------------------------------
    # 输出结果
    # --------------------------------------------------------

    print("\n【输入参数】")

    print(f"期货价格 F      : {F:.2f}")
    print(f"行权价 K        : {K:.2f}")
    print(f"剩余时间        : {remaining_days} 天")
    print(f"波动率 IV        : {sigma * 100:.2f}%")
    print(f"利率 r           : {r * 100:.2f}%")

    print("\n【Black-76 理论价格】")

    print(f"Put 理论价格     : {put_price:.4f}")

    print("\n【Greeks】")

    print(f"Delta            : {greeks['delta']:.6f}")
    print(f"Gamma            : {greeks['gamma']:.8f}")
    print(f"Vega             : {greeks['vega']:.4f}")
    print(f"Theta / 天       : {greeks['theta']:.4f}")

    print("\n" + "=" * 70)


if __name__ == "__main__":
    main()
